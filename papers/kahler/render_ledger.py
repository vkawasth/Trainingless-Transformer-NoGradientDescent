"""Render LEDGER.yaml (repository root) to kahler/ledger_table.tex for the appendix of the companion note. The rendered file is checked to be up
to date by engine/check_ledger.py (LG3)."""
import os, sys, yaml
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
TAG = {"Proved": "P", "Used": "U", "Cited": "C", "Exact": "E", "Numerical": "N", "Defined": "D", "Open": "O", "N/A": "--"}
def tex(s):
    s = str(s)
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#"), ("^", "\\^{}"), ("~", "\\~{}"), ("|", "\x00vert"), ('"', "''")): s = s.replace(a, b)
    s = s.replace("!=", "\x00ne").replace("<=", "\x00le").replace(">=", "\x00ge").replace("->", "\x00to").replace("<", "\x00langle").replace(">", "\x00rangle")
    for k in ("ne", "le", "ge", "to", "langle", "rangle", "vert"): s = s.replace("\x00" + k, "$\\" + k + "$")
    return s
def render(path=os.path.join(ROOT, "LEDGER.yaml")):
    L = yaml.safe_load(open(path)); out = ["% generated by kahler/render_ledger.py from LEDGER.yaml; do not edit", "{\\scriptsize\\setlength{\\tabcolsep}{3pt}",
        "\\begin{longtable}{*{5}{>{\\raggedright\\arraybackslash}p{0.177\\linewidth}}}\\toprule",
        "operation & contingency / toric & mirror ($W$, $\\lambda$) & Floer (cited); category & wall certificate; checks\\\\\\midrule\\endhead"]
    for r in L["rows"]:
        lv = r["levels"]; cell = lambda k: f"[{TAG[lv[k]['status']]}] " + tex(lv[k]["text"])
        out.append(f"\\textbf{{{tex(r['id'])}}}: {tex(r['operation'])} & {cell('contingency')}; {cell('toric')} & {cell('mirror')} & {cell('floer')}; "
                   f"category {cell('category')} & {tex(r['wall_certificate'])}; \\textsc{{checks}} {', '.join(r['checks']) or '--'}\\\\")
    out += ["\\bottomrule\\end{longtable}}"]; return "\n".join(out) + "\n"
if __name__ == "__main__":
    open(os.path.join(HERE, "ledger_table.tex"), "w").write(render()); print("ok")
