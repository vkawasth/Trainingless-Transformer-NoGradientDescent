"""
check_span.py

Verifies the two-shadow decomposition of the shift law's (Cm) defect
and the span axioms on two-, three-, and four-point bases.

Uses hypothesis inputs so that L and R are genuinely different.

Run: python check_span.py
"""

from fractions import Fraction
import random
import hashlib
import json


# ============================================================
# Canonical distributions
# ============================================================

def canonical(d):
    return tuple(sorted(d.items(), key=lambda kv: repr(kv[0])))


def mk(items):
    d = {}
    for k, p in items:
        d[k] = d.get(k, Fraction(0)) + Fraction(p)
    return canonical(d)


def push(d, f):
    return mk([(f(k), p) for k, p in d])


def barycenter(dd):
    out = {}
    for rho_key, p in dd:
        for b, q in rho_key:
            out[b] = out.get(b, Fraction(0)) + p * q
    return canonical(out)


def tv(d1, d2):
    a = dict(d1)
    b = dict(d2)
    keys = set(a) | set(b)
    return sum(abs(a.get(k, Fraction(0)) - b.get(k, Fraction(0)))
               for k in keys) / 2


def is_dist(x):
    if not isinstance(x, tuple) or len(x) == 0:
        return False
    for item in x:
        if not (isinstance(item, tuple) and len(item) == 2):
            return False
    return True


def is_hypothesis(x):
    return (isinstance(x, tuple) and len(x) == 2
            and isinstance(x[0], int) and is_dist(x[1]))


def dist_of(x):
    if is_hypothesis(x):
        return x[1]
    return x


def type_aware_distance(a, b):
    if is_dist(a) and is_dist(b):
        return tv(a, b)
    if is_hypothesis(a) and is_hypothesis(b):
        if a[0] != b[0]:
            return Fraction(1)
        return tv(a[1], b[1])
    if (is_dist(a) and is_hypothesis(b)) or (is_hypothesis(a) and is_dist(b)):
        return tv(dist_of(a), dist_of(b))
    return Fraction(1)


# ============================================================
# Barycentric pooling
# ============================================================

def pooling_conditional_expectation(nu, atoms):
    """
    Barycentric pooling of nu onto the sigma-algebra generated by atoms.
    """
    d = dict(nu)
    groups = {}
    for k, p in d.items():
        best = None
        best_d = None
        for a in atoms:
            dist = type_aware_distance(k, a)
            if best_d is None or dist < best_d:
                best_d = dist
                best = a
        if best is None:
            continue
        groups.setdefault(best, []).append((k, p))

    out = {}
    for a, members in groups.items():
        mass = sum(p for _, p in members)
        if mass == 0:
            continue
        weighted = {}
        for k, p in members:
            dist_k = dist_of(k)
            for b, q in dict(dist_k).items():
                weighted[b] = weighted.get(b, Fraction(0)) + (p / mass) * q
        bary = canonical(weighted)
        out[bary] = out.get(bary, Fraction(0)) + mass
    return canonical(out)


# ============================================================
# The tower context
# ============================================================

def random_rho(n, rng):
    weights = [rng.randint(1, 5) for _ in range(n)]
    return mk([(i, w) for i, w in enumerate(weights)])


def random_coherent_context(n, rng):
    """
    Coherent context with a shadow whose hypotheses have multiple descriptors.
    """
    rho1 = random_rho(n, rng)
    rho2 = random_rho(n, rng)
    while rho1 == rho2:
        rho2 = random_rho(n, rng)

    w11 = Fraction(rng.randint(1, 4), 5)
    Pi1 = mk([(rho1, w11), (rho2, 1 - w11)])
    w21 = Fraction(rng.randint(1, 4), 5)
    Pi2 = mk([(rho1, w21), (rho2, 1 - w21)])

    omega1 = Fraction(rng.randint(1, 4), 5)
    Omega = mk([(Pi1, omega1), (Pi2, 1 - omega1)])

    Pi = barycenter(Omega)
    rho = barycenter(Pi)

    # Shadow with two descriptors, alternating across the atoms of Pi.
    items = list(dict(Pi).items())
    Sigma = mk([((i % 2, j), w) for i, (j, w) in enumerate(items)])

    return (rho, Pi, Omega, Sigma)


# ============================================================
# The two shadows
# ============================================================

def L_atoms(Pi):
    return list(dict(Pi).keys())


def R_atoms(Sigma):
    return list(dict(Sigma).keys())


def L_shadow(x, c, nu):
    rho, Pi, Omega, Sigma = c
    return pooling_conditional_expectation(nu, L_atoms(Pi))


def R_shadow(x, c, nu):
    rho, Pi, Omega, Sigma = c
    return pooling_conditional_expectation(nu, R_atoms(Sigma))


# ============================================================
# Inputs
# ============================================================

def make_dist_input(n):
    """A distribution over D(B): uniform over point masses."""
    return mk([(mk([(b, Fraction(1))]), Fraction(1, n)) for b in range(n)])


def make_hypothesis_input(n, Sigma):
    """
    A distribution over hypotheses: uniform over the hypotheses of Sigma.
    This is the input that makes L and R genuinely different.
    """
    items = list(dict(Sigma).items())
    if not items:
        return mk([((0, mk([(0, Fraction(1))])), Fraction(1))])
    return mk([(h, Fraction(1, len(items))) for h, _ in items])


def make_mixed_input(n, Sigma):
    """
    A mixed input: half distribution over point masses, half over hypotheses.
    """
    dist_part = mk([(mk([(b, Fraction(1))]), Fraction(1, 2 * n)) for b in range(n)])
    items = list(dict(Sigma).items())
    hyp_part = mk([(h, Fraction(1, 2 * len(items))) for h, _ in items])
    # Combine
    combined = {}
    for k, p in dict(dist_part).items():
        combined[k] = combined.get(k, Fraction(0)) + p
    for k, p in dict(hyp_part).items():
        combined[k] = combined.get(k, Fraction(0)) + p
    return canonical(combined)


# ============================================================
# Span axioms
# ============================================================

def check_span(n, n_trials, seed, input_type="hypothesis"):
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_coherent_context(n, rng)
        x = rng.randint(0, n - 1)

        if input_type == "distribution":
            nu = make_dist_input(n)
        elif input_type == "hypothesis":
            nu = make_hypothesis_input(n, c[3])
        elif input_type == "mixed":
            nu = make_mixed_input(n, c[3])
        else:
            nu = make_dist_input(n)

        L = L_shadow(x, c, nu)
        R = R_shadow(x, c, nu)

        well_defined = is_dist(L) and is_dist(R)
        not_inverse_LR = (L != nu)
        not_inverse_RL = (R != nu)
        different = (L != R)

        results.append({
            "trial": trial,
            "well_defined": well_defined,
            "not_inverse_LR": not_inverse_LR,
            "not_inverse_RL": not_inverse_RL,
            "different": different,
        })
    return results


def check_idempotent(n, n_trials, seed, input_type="hypothesis"):
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_coherent_context(n, rng)
        x = rng.randint(0, n - 1)

        if input_type == "distribution":
            nu = make_dist_input(n)
        elif input_type == "hypothesis":
            nu = make_hypothesis_input(n, c[3])
        else:
            nu = make_mixed_input(n, c[3])

        L = L_shadow(x, c, nu)
        LL = L_shadow(x, c, L)
        R = R_shadow(x, c, nu)
        RR = R_shadow(x, c, R)

        results.append({
            "trial": trial,
            "L_idempotent": L == LL,
            "R_idempotent": R == RR,
        })
    return results


def check_barycenter(n, n_trials, seed, input_type="hypothesis"):
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_coherent_context(n, rng)
        x = rng.randint(0, n - 1)

        if input_type == "distribution":
            nu = make_dist_input(n)
        elif input_type == "hypothesis":
            nu = make_hypothesis_input(n, c[3])
        else:
            nu = make_mixed_input(n, c[3])

        # Barycenter of nu: extract distributions from hypotheses
        mu_nu = {}
        for k, p in dict(nu).items():
            d = dist_of(k)
            for b, q in dict(d).items():
                mu_nu[b] = mu_nu.get(b, Fraction(0)) + p * q
        mu_nu = canonical(mu_nu)

        L = L_shadow(x, c, nu)
        mu_L = {}
        for k, p in dict(L).items():
            d = dist_of(k)
            for b, q in dict(d).items():
                mu_L[b] = mu_L.get(b, Fraction(0)) + p * q
        mu_L = canonical(mu_L)

        R = R_shadow(x, c, nu)
        mu_R = {}
        for k, p in dict(R).items():
            d = dist_of(k)
            for b, q in dict(d).items():
                mu_R[b] = mu_R.get(b, Fraction(0)) + p * q
        mu_R = canonical(mu_R)

        results.append({
            "trial": trial,
            "L_preserves": mu_nu == mu_L,
            "R_preserves": mu_nu == mu_R,
        })
    return results


def check_cm_equals_sum(n, n_trials, seed, input_type="hypothesis"):
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_coherent_context(n, rng)
        x = rng.randint(0, n - 1)

        if input_type == "distribution":
            nu = make_dist_input(n)
        elif input_type == "hypothesis":
            nu = make_hypothesis_input(n, c[3])
        else:
            nu = make_mixed_input(n, c[3])

        L = L_shadow(x, c, nu)
        R = R_shadow(x, c, nu)

        defect = (L, R)
        sum_ = (L_shadow(x, c, nu), R_shadow(x, c, nu))

        results.append({
            "trial": trial,
            "defect_equals_sum": defect == sum_,
        })
    return results


# ============================================================
# Main
# ============================================================

def run_all(n, n_trials, seed, label, input_type="hypothesis"):
    print(f"=== {label} (n = {n}, trials = {n_trials}, input = {input_type}) ===")
    span = check_span(n, n_trials, seed, input_type)
    idem = check_idempotent(n, n_trials, seed + 1, input_type)
    bary = check_barycenter(n, n_trials, seed + 2, input_type)
    cm = check_cm_equals_sum(n, n_trials, seed + 3, input_type)

    n_well = sum(1 for r in span if r["well_defined"])
    n_not_inv_LR = sum(1 for r in span if r["not_inverse_LR"])
    n_not_inv_RL = sum(1 for r in span if r["not_inverse_RL"])
    n_diff = sum(1 for r in span if r["different"])
    n_L_idem = sum(1 for r in idem if r["L_idempotent"])
    n_R_idem = sum(1 for r in idem if r["R_idempotent"])
    n_L_bary = sum(1 for r in bary if r["L_preserves"])
    n_R_bary = sum(1 for r in bary if r["R_preserves"])
    n_cm = sum(1 for r in cm if r["defect_equals_sum"])

    print(f"  well-defined: {n_well}/{n_trials}")
    print(f"  L not inverse of nu: {n_not_inv_LR}/{n_trials}")
    print(f"  R not inverse of nu: {n_not_inv_RL}/{n_trials}")
    print(f"  L different from R: {n_diff}/{n_trials}")
    print(f"  L idempotent: {n_L_idem}/{n_trials}")
    print(f"  R idempotent: {n_R_idem}/{n_trials}")
    print(f"  L preserves barycenter: {n_L_bary}/{n_trials}")
    print(f"  R preserves barycenter: {n_R_bary}/{n_trials}")
    print(f"  (Cm) defect equals sum: {n_cm}/{n_trials}")
    print()

    return {
        "label": label,
        "n": n,
        "n_trials": n_trials,
        "input_type": input_type,
        "well_defined": n_well,
        "not_inverse_LR": n_not_inv_LR,
        "not_inverse_RL": n_not_inv_RL,
        "different": n_diff,
        "L_idempotent": n_L_idem,
        "R_idempotent": n_R_idem,
        "L_barycenter": n_L_bary,
        "R_barycenter": n_R_bary,
        "cm_equals_sum": n_cm,
    }


def freeze(results, filename="check_span_results.json"):
    with open(filename, "w") as f:
        json.dump(results, f, indent=2, default=str)
    with open(filename, "rb") as f:
        h = hashlib.sha256(f.read()).hexdigest()
    print(f"SHA-256: {h}")
    return h


if __name__ == "__main__":
    all_results = []

    # Distribution inputs (L = R expected)
    all_results.append(run_all(2, 300, 42, "two-point base", "distribution"))
    all_results.append(run_all(3, 300, 42, "three-point base", "distribution"))
    all_results.append(run_all(4, 300, 42, "four-point base", "distribution"))

    # Hypothesis inputs (L != R expected)
    all_results.append(run_all(2, 300, 42, "two-point base", "hypothesis"))
    all_results.append(run_all(3, 300, 42, "three-point base", "hypothesis"))
    all_results.append(run_all(4, 300, 42, "four-point base", "hypothesis"))

    # Mixed inputs
    all_results.append(run_all(2, 300, 42, "two-point base", "mixed"))
    all_results.append(run_all(3, 300, 42, "three-point base", "mixed"))
    all_results.append(run_all(4, 300, 42, "four-point base", "mixed"))

    freeze(all_results)
