"""
check_giry.py

Verifies the structural properties of the Giry extension of the tower
on a finite discretization of a standard Borel space.

The Giry monad G on a finite discretization is the finite distribution
monad D, but the disintegrations are computed as conditional expectations
on the discretized σ-algebra.

Run: python check_giry.py
"""

from fractions import Fraction
import random
import hashlib
import json


# ============================================================
# Canonical distributions
# ============================================================

def canonical(d):
    return tuple(sorted(d.items(), key=lambda kv: repr(kv[0])))


def mk(items):
    d = {}
    for k, p in items:
        d[k] = d.get(k, Fraction(0)) + Fraction(p)
    return canonical(d)


def push(d, f):
    return mk([(f(k), p) for k, p in d])


def barycenter(dd):
    """Barycenter of a distribution over distributions."""
    out = {}
    for rho_key, p in dd:
        for b, q in rho_key:
            out[b] = out.get(b, Fraction(0)) + p * q
    return canonical(out)


def tv(d1, d2):
    a = dict(d1)
    b = dict(d2)
    keys = set(a) | set(b)
    return sum(abs(a.get(k, Fraction(0)) - b.get(k, Fraction(0)))
               for k in keys) / 2


def is_dist(x):
    if not isinstance(x, tuple) or len(x) == 0:
        return False
    for item in x:
        if not (isinstance(item, tuple) and len(item) == 2):
            return False
    return True


def is_hypothesis(x):
    return (isinstance(x, tuple) and len(x) == 2
            and isinstance(x[0], int) and is_dist(x[1]))


def dist_of(x):
    if is_hypothesis(x):
        return x[1]
    return x


def type_aware_distance(a, b):
    if is_dist(a) and is_dist(b):
        return tv(a, b)
    if is_hypothesis(a) and is_hypothesis(b):
        if a[0] != b[0]:
            return Fraction(1)
        return tv(a[1], b[1])
    if (is_dist(a) and is_hypothesis(b)) or (is_hypothesis(a) and is_dist(b)):
        return tv(dist_of(a), dist_of(b))
    return Fraction(1)


# ============================================================
# Barycentric pooling (the finite approximation of the disintegration)
# ============================================================

def pooling(nu, atoms):
    """
    Barycentric pooling of nu onto the sigma-algebra generated by atoms.
    This is the finite approximation of the Giry disintegration.
    """
    d = dict(nu)
    groups = {}
    for k, p in d.items():
        best = None
        best_d = None
        for a in atoms:
            dist = type_aware_distance(k, a)
            if best_d is None or dist < best_d:
                best_d = dist
                best = a
        if best is None:
            continue
        groups.setdefault(best, []).append((k, p))

    out = {}
    for a, members in groups.items():
        mass = sum(p for _, p in members)
        if mass == 0:
            continue
        weighted = {}
        for k, p in members:
            dk = dist_of(k)
            for b, q in dict(dk).items():
                weighted[b] = weighted.get(b, Fraction(0)) + (p / mass) * q
        bary = canonical(weighted)
        out[bary] = out.get(bary, Fraction(0)) + mass
    return canonical(out)


# ============================================================
# The Giry context
# ============================================================

def random_giry_context(n, rng):
    """
    A coherent context on a finite discretization of a standard Borel space.
    The Giry monad G on the discretization is the finite distribution monad.
    """
    rho1 = mk([(i, Fraction(rng.randint(1, 5), 1)) for i in range(n)])
    rho2 = mk([(i, Fraction(rng.randint(1, 5), 1)) for i in range(n)])
    while rho1 == rho2:
        rho2 = mk([(i, Fraction(rng.randint(1, 5), 1)) for i in range(n)])

    w11 = Fraction(rng.randint(1, 4), 5)
    Pi1 = mk([(rho1, w11), (rho2, 1 - w11)])
    w21 = Fraction(rng.randint(1, 4), 5)
    Pi2 = mk([(rho1, w21), (rho2, 1 - w21)])

    omega1 = Fraction(rng.randint(1, 4), 5)
    Omega = mk([(Pi1, omega1), (Pi2, 1 - omega1)])

    Pi = barycenter(Omega)
    rho = barycenter(Pi)

    items = list(dict(Pi).items())
    Sigma = mk([((i % 2, j), w) for i, (j, w) in enumerate(items)])

    return (rho, Pi, Omega, Sigma)


# ============================================================
# The Giry shadows
# ============================================================

def L_shadow(x, c, nu):
    """
    L-shadow: disintegration onto the sigma-algebra generated by Pi-atoms.
    """
    rho, Pi, Omega, Sigma = c
    return pooling(nu, list(dict(Pi).keys()))


def R_shadow(x, c, nu):
    """
    R-shadow: disintegration onto the sigma-algebra generated by Sigma-hypotheses.
    """
    rho, Pi, Omega, Sigma = c
    return pooling(nu, list(dict(Sigma).keys()))


# ============================================================
# The Giry checks
# ============================================================

def check_interchange(n, n_trials, seed):
    """
    Interchange law: R(L(nu)) = L(R(nu)).
    """
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_giry_context(n, rng)
        x = rng.randint(0, n - 1)
        nu = mk([(mk([(b, Fraction(1))]), Fraction(1, n)) for b in range(n)])

        LR = R_shadow(x, c, L_shadow(x, c, nu))
        RL = L_shadow(x, c, R_shadow(x, c, nu))

        results.append({
            "trial": trial,
            "interchange": LR == RL,
        })
    return results


def check_idempotent(n, n_trials, seed):
    """
    Idempotence: L(L(nu)) = L(nu), R(R(nu)) = R(nu).
    """
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_giry_context(n, rng)
        x = rng.randint(0, n - 1)
        nu = mk([(mk([(b, Fraction(1))]), Fraction(1, n)) for b in range(n)])

        L = L_shadow(x, c, nu)
        LL = L_shadow(x, c, L)
        R = R_shadow(x, c, nu)
        RR = R_shadow(x, c, R)

        results.append({
            "trial": trial,
            "L_idempotent": L == LL,
            "R_idempotent": R == RR,
        })
    return results


def check_barycenter(n, n_trials, seed):
    """
    Barycenter preservation: mu(L(nu)) = mu(nu), mu(R(nu)) = mu(nu).
    """
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_giry_context(n, rng)
        x = rng.randint(0, n - 1)
        nu = mk([(mk([(b, Fraction(1))]), Fraction(1, n)) for b in range(n)])

        mu_nu = barycenter(nu)

        L = L_shadow(x, c, nu)
        mu_L = barycenter(L)

        R = R_shadow(x, c, nu)
        mu_R = barycenter(R)

        results.append({
            "trial": trial,
            "L_preserves": mu_nu == mu_L,
            "R_preserves": mu_nu == mu_R,
        })
    return results


def check_3cell(n, n_trials, seed):
    """
    3-cell triviality: the two composition orders agree.
    """
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_giry_context(n, rng)
        x = rng.randint(0, n - 1)
        nu = mk([(mk([(b, Fraction(1))]), Fraction(1, n)) for b in range(n)])

        rho, Pi, Omega, Sigma = c
        atoms_4 = list(dict(Pi).keys())
        atoms_5 = list(dict(push(Pi, lambda r: mk([(r, Fraction(1))]))).keys())

        comp_45 = pooling(pooling(nu, atoms_4), atoms_5)
        comp_54 = pooling(pooling(nu, atoms_5), atoms_4)

        results.append({
            "trial": trial,
            "three_cell_trivial": comp_45 == comp_54,
        })
    return results


def check_giry_disintegration(n, n_trials, seed):
    """
    Giry disintegration: verify that the pooling operation is a disintegration
    on the finite discretization.
    The disintegration property is:
    - The pooling is a conditional expectation.
    - The pooling preserves the measure on the sigma-algebra.
    """
    rng = random.Random(seed)
    results = []
    for trial in range(n_trials):
        c = random_giry_context(n, rng)
        x = rng.randint(0, n - 1)
        nu = mk([(mk([(b, Fraction(1))]), Fraction(1, n)) for b in range(n)])

        rho, Pi, Omega, Sigma = c
        atoms = list(dict(Pi).keys())
        L = pooling(nu, atoms)

        # The disintegration property: for each atom, the conditional
        # distribution is a probability measure.
        is_prob = True
        for k, p in dict(L).items():
            total = sum(q for _, q in dict(k).items())
            if total != 1:
                is_prob = False
                break

        results.append({
            "trial": trial,
            "is_probability": is_prob,
        })
    return results


# ============================================================
# Main
# ============================================================

def run_all(n, n_trials, seed, label):
    print(f"=== {label} (n = {n}, trials = {n_trials}) ===")
    inter = check_interchange(n, n_trials, seed)
    idem = check_idempotent(n, n_trials, seed + 1)
    bary = check_barycenter(n, n_trials, seed + 2)
    three = check_3cell(n, n_trials, seed + 3)
    dis = check_giry_disintegration(n, n_trials, seed + 4)

    n_inter = sum(1 for r in inter if r["interchange"])
    n_L_idem = sum(1 for r in idem if r["L_idempotent"])
    n_R_idem = sum(1 for r in idem if r["R_idempotent"])
    n_L_bary = sum(1 for r in bary if r["L_preserves"])
    n_R_bary = sum(1 for r in bary if r["R_preserves"])
    n_3cell = sum(1 for r in three if r["three_cell_trivial"])
    n_prob = sum(1 for r in dis if r["is_probability"])

    print(f"  interchange: {n_inter}/{n_trials}")
    print(f"  L idempotent: {n_L_idem}/{n_trials}")
    print(f"  R idempotent: {n_R_idem}/{n_trials}")
    print(f"  L preserves barycenter: {n_L_bary}/{n_trials}")
    print(f"  R preserves barycenter: {n_R_bary}/{n_trials}")
    print(f"  3-cell trivial: {n_3cell}/{n_trials}")
    print(f"  disintegration is probability: {n_prob}/{n_trials}")
    print()

    return {
        "label": label,
        "n": n,
        "n_trials": n_trials,
        "interchange": n_inter,
        "L_idempotent": n_L_idem,
        "R_idempotent": n_R_idem,
        "L_barycenter": n_L_bary,
        "R_barycenter": n_R_bary,
        "3cell": n_3cell,
        "disintegration_probability": n_prob,
    }


def freeze(results, filename="check_giry_results.json"):
    with open(filename, "w") as f:
        json.dump(results, f, indent=2, default=str)
    with open(filename, "rb") as f:
        h = hashlib.sha256(f.read()).hexdigest()
    print(f"SHA-256: {h}")
    return h


if __name__ == "__main__":
    all_results = []
    all_results.append(run_all(2, 300, 42, "two-point base"))
    all_results.append(run_all(3, 300, 42, "three-point base"))
    all_results.append(run_all(4, 300, 42, "four-point base"))
    all_results.append(run_all(5, 300, 42, "five-point base"))
    freeze(all_results)
