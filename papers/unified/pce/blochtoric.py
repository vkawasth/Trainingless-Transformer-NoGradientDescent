"""Phases of the Floer objects of Part IV as angular data (companion note, section on Bloch pictures). New module; it modifies nothing and
uses pce/cpl24.py.
  objects(ex, L)              the critical points of example ex at T = e^-L: valuation u = -log|y| / L and leading holonomy theta = arg y
  rounded(objs, den)          u and theta / pi rounded to rationals (theta / pi to multiples of 1/den)
  holonomy_group(thetas)      for a finite set S of holonomies (in units of pi, mod 2): whether S - s0 is a subgroup of the torus, and its order
  invariant_factors(S)        the invariant factors of the finite abelian group S - s0 (Smith normal form of its relation lattice)
  qubit(p, theta)             the qubit state sqrt(1 - p)|0> + sqrt(p) e^{i theta}|1>
  bloch(p, theta)             its Bloch vector (2 sqrt(p(1-p)) cos theta, 2 sqrt(p(1-p)) sin theta, 1 - 2p)
  fs_metric(p, dp, dtheta)    the Fubini-Study line element of z = sqrt(p) e^{i theta} (any number of components), computed from
                              <dz, dz> - |<z, dz>|^2
  identify(thetas, U)         the images of holonomies under a lattice identification U in GL(3, Z) (mod 2 in units of pi)
"""
from __future__ import annotations
import itertools
from fractions import Fraction as Fr
import numpy as np
import mpmath as mp
from . import cpl24 as C


def objects(ex, L):
    f, g = ex; pts, bound = C.critical_points_exact(f, g, L)
    return [(np.array([float(-mp.log(abs(c)) / L) for c in y]), np.array([float(mp.arg(c)) for c in y])) for y in pts], bound


def rounded(objs, den=12, uden=240):
    out = []
    for u, th in objs:
        uu = tuple(Fr(round(float(x) * uden), uden) for x in u)
        tt = tuple(Fr(round(float(t) / np.pi * den) % (2 * den), den) for t in th)        # theta / pi in [0, 2)
        out.append((uu, tt))
    return out


def _sub(a, b): return tuple((x - y) % 2 for x, y in zip(a, b))
def _add(a, b): return tuple((x + y) % 2 for x, y in zip(a, b))


def holonomy_group(S):
    S = list(dict.fromkeys(S)); s0 = S[0]; D = set(_sub(s, s0) for s in S)
    closed = all(_add(a, b) in D for a in D for b in D)
    return closed, len(D), D


def invariant_factors(D):
    """D: a finite subgroup of (Q/2Z)^3 (units of pi). Write elements as integer vectors over the common denominator n (so the group sits in
    (Z / 2n)^3); the group is generated by D; its invariant factors are those of Z^k / (relations), computed via the Smith normal form of the
    lattice spanned by D and 2n Z^3."""
    import sympy as sp
    n = 1
    for v in D:
        for x in v: n = sp.ilcm(n, Fr(x).denominator)
    gens = [[int(Fr(x) * n) for x in v] for v in D] + [[2 * n if i == j else 0 for j in range(3)] for i in range(3)]
    Lm = sp.Matrix(gens)                                                  # rows span the lattice Lambda = <D> + 2n Z^3 inside Z^3
    from sympy.matrices.normalforms import smith_normal_form
    S = smith_normal_form(Lm, domain=sp.ZZ); diag = [abs(S[i, i]) for i in range(3)]
    # <D> ~ Lambda / 2n Z^3 ; |Lambda / 2n Z^3| = (2n)^3 / prod(diag); invariant factors of Lambda / 2n Z^3 = 2n / diag_i
    return sorted(int(2 * n // d) for d in diag if 2 * n // d > 1)


def qubit(p, theta): return np.array([np.sqrt(1 - p), np.sqrt(p) * np.exp(1j * theta)])


def bloch(p, theta):
    r = 2 * np.sqrt(p * (1 - p)); return np.array([r * np.cos(theta), r * np.sin(theta), 1 - 2 * p])


def fs_metric(p, dp, dth):
    p, dp, dth = (np.asarray(a, float) for a in (p, dp, dth))
    z = np.sqrt(p) * np.exp(0j); dz = (dp / (2 * np.sqrt(p)) + 1j * np.sqrt(p) * dth)
    return float(np.vdot(dz, dz).real - abs(np.vdot(z, dz)) ** 2)


def identify(S, U):
    U = np.asarray(U, int); return set(tuple(Fr(int(round(float(sum(U[i, j] * Fr(t[j]) for j in range(3))) * 1e6)), 10 ** 6) % 2 for i in range(3)) for t in S)
