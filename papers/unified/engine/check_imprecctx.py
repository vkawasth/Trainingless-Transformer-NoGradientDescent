"""Checks for 'imprecision without contextuality' (module pce/imprecctx.py). Three tied pairs; resolution of pair (a, b) = which side
of its wall the difference of the global direction falls on; walls are lines through 0 with angle alpha_ab.
  IC1 IDENTITY  parallel walls (ties along one direction, e.g. one-dimensional reports): the realisable patterns are exactly the 6 total
                orders; generic walls: all 8 patterns are realisable
  IC2 IDENTITY  parallel walls: single-pair data p_ab = P(a resolved before b) have a global law iff 1 <= p_01 + p_12 + (1 - p_02) <= 2
                (1000 random data points); with generic walls every such data point has one
  IC3 IDENTITY  the Condorcet cycle (0 before 1, 1 before 2, 2 before 0, each with probability 0.9) has no global law: contextual
  IC4 IDENTITY  imprecision without contextuality: on every feasible data point the probability of the order 0 < 1 < 2 ranges over
                [max(0, p_01 + p_12 - 1), min(p_01, p_02, p_12, p_01 + p_12 - p_02)] (LP against the formula, 1000
                points); of positive width on all of them. (A first version omitted the last term of the upper bound; it failed on 724 of
                3000 points and was corrected by solving the six-order LP by hand.)
  IC5 IDENTITY  data generated by any law on global directions (here correlated Gaussians, 300 laws) are always feasible: global
                assignments never give contextual data
"""
import os, sys, json, itertools
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from pce import imprecctx as IC
results = []
def check(name, cond, info=""):
    results.append(bool(cond)); print(("PASS " if cond else "FAIL ") + name + (f"   [{info}]" if info else ""), flush=True)
rng = np.random.default_rng(13)
pairs, O = IC.orders(3)

# IC1
col = [lambda om, a=a, b=b: int(om[a].real < om[b].real) for a, b in pairs]
al = {(0, 1): 0.3, (0, 2): 1.4, (1, 2): 2.2}
gen = [lambda om, a=a, b=b: int((np.exp(-1j * al[(a, b)]) * (om[a] - om[b])).imag > 0) for a, b in pairs]
Rc = IC.realisable_patterns(col, 3, 4000, rng); Rg = IC.realisable_patterns(gen, 3, 4000, rng); allp = sorted(itertools.product((0, 1), repeat=3))
check("IC1 IDENTITY parallel walls: patterns = the 6 total orders; generic walls: all 8", Rc == O and Rg == allp, f"parallel {len(Rc)}, generic {len(Rg)}")

# IC2
ok = True; bad = 0
for _ in range(1000):
    p = rng.uniform(0, 1, 3); t = dict(zip(pairs, p)); s = p[0] + p[2] + (1 - p[1])
    ok &= IC.global_feasible(O, pairs, t) == (1 - 1e-9 <= s <= 2 + 1e-9); ok &= IC.global_feasible(Rg, pairs, t); bad += not (1 <= s <= 2)
check("IC2 IDENTITY parallel walls: feasible iff 1 <= p01 + p12 + (1 - p02) <= 2; generic walls: always feasible", ok, f"{bad} of 1000 random points infeasible for parallel walls")

# IC3
t = {(0, 1): 0.9, (1, 2): 0.9, (0, 2): 0.1}
check("IC3 IDENTITY the Condorcet cycle has no global law", not IC.global_feasible(O, pairs, t) and IC.global_feasible(Rg, pairs, t))

# IC4
ok = True; cnt = 0; widths = []
while cnt < 1000:
    p = rng.uniform(0, 1, 3); t = dict(zip(pairs, p))
    if not IC.global_feasible(O, pairs, t): continue
    lo, hi = IC.bounds(O, pairs, t, {(1, 1, 1)}); flo, fhi = max(0.0, p[0] + p[2] - 1), min(p[0], p[2], p[1], p[0] + p[2] - p[1])
    ok &= abs(lo - flo) < 1e-7 and abs(hi - fhi) < 1e-7 and hi - lo > 1e-6; widths.append(hi - lo); cnt += 1
check("IC4 IDENTITY imprecision without contextuality: P(0<1<2) in [max(0, p01 + p12 - 1), min(p01, p02, p12, p01 + p12 - p02)], positive width", ok,
      f"1000 feasible points; widths from {min(widths):.3f} to {max(widths):.3f}, mean {np.mean(widths):.3f}")

# IC5
ok = True
for _ in range(300):
    A = rng.standard_normal((3, 3)); S = A @ A.T + 0.1 * np.eye(3); m = rng.standard_normal(3)
    om = rng.multivariate_normal(m, S, 4000); p = [float(np.mean(om[:, a] < om[:, b])) for a, b in pairs]
    ok &= IC.global_feasible(O, pairs, dict(zip(pairs, p)))
check("IC5 IDENTITY data from any law on global directions are feasible (never contextual)", ok, "300 random correlated Gaussian laws")
json.dump(dict(widths_mean=float(np.mean(widths))), open(os.path.join(HERE, "imprecctx_summary.json"), "w"), indent=1)
print(f"{sum(results)}/{len(results)} passed")
