"""Exact (Groebner) computation of the scheme-theoretic fibre of the two-type latent-class map over a product law.
Coordinates: w1 (w2 = 1 - w1), mean mu = w1 a1 + w2 a2, difference d = a1 - a2 (a polynomial automorphism: a1 = mu + w2 d, a2 = mu - w1 d)."""
import itertools, sys, time
import sympy as sp

def run(m, c):
    w1 = sp.Symbol("w1"); w2 = 1 - w1
    mu = sp.symbols(f"mu1:{m+1}"); d = sp.symbols(f"d1:{m+1}")
    a1 = [mu[i] + w2 * d[i] for i in range(m)]; a2 = [mu[i] - w1 * d[i] for i in range(m)]
    def prod(a, x): return sp.Mul(*[(a[i] if x[i] else 1 - a[i]) for i in range(m)])
    atoms = list(itertools.product([0, 1], repeat=m))
    P = {x: prod(c, x) for x in atoms}
    gens = [sp.expand(w1 * prod(a1, x) + w2 * prod(a2, x) - P[x]) for x in atoms]
    # 1. global normal form: central moments of the mixture are c_S(w) d_S
    ok_moments = True
    for k in range(2, m + 1):
        for S in itertools.combinations(range(m), k):
            cm = sp.expand(w1 * sp.Mul(*[a1[i] - mu[i] for i in S]) + w2 * sp.Mul(*[a2[i] - mu[i] for i in S]))
            cS = w1 * w2 ** k + w2 * (-w1) ** k
            ok_moments &= sp.expand(cm - cS * sp.Mul(*[d[i] for i in S])) == 0
    # 2. the fibre ideal over the product law equals (mu - c) + (w1 w2 d_i d_j)
    vars_ = list(d) + [w1] + list(mu)
    G1 = sp.groebner(gens, *vars_, order="grevlex")
    target = [mu[i] - c[i] for i in range(m)] + [w1 * w2 * d[i] * d[j] for i, j in itertools.combinations(range(m), 2)]
    G2 = sp.groebner(target, *vars_, order="grevlex")
    same = all(G2.contains(g) for g in G1.exprs) and all(G1.contains(g) for g in G2.exprs)
    # 3. primary decomposition: I = (mu-c, w1) n (mu-c, w2) n_i (mu-c, d_j : j != i), checked by membership both ways
    comps = [[w1], [w2]] + [[d[j] for j in range(m) if j != i] for i in range(m)]
    lin = [mu[i] - c[i] for i in range(m)]
    in_all = all(sp.groebner(lin + C, *vars_, order="grevlex").contains(g) for C in comps for g in G1.exprs)
    # the intersection is contained in I: a product of one generator from each component lies in I, and the components' generators
    # are variables (squarefree monomial ideal after the linear change), so the intersection is generated by the lcm-products
    prods_in = True
    for choice in itertools.product(*comps):
        prods_in &= G1.contains(sp.expand(sp.Mul(*set(choice))))
    return ok_moments, same, in_all, prods_in, G1

for m in (3, 4):
    c = [sp.Rational(2, 5), sp.Rational(1, 2), sp.Rational(3, 5), sp.Rational(1, 3)][:m]
    t = time.time(); r = run(m, c)
    print(f"m={m}: central moments = c_S(w) d_S: {r[0]};  fibre ideal = (mu - c, w1 w2 d_i d_j): {r[1]};  "
          f"I inside every component: {r[2]};  intersection inside I: {r[3]}   ({time.time()-t:.1f}s)")
    if m == 3: print("  reduced Groebner basis:", r[4].exprs)
