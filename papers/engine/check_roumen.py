"""check_roumen.py -- Roumen's cohomology of effect algebras on the lab's contextual families, and injection as a soft intervention
(lab paper, Section "Markov categories", paragraphs "Roumen's order cohomology" and "Injection as a soft intervention").

Roumen (EPTCS 236 (2017) 174-201). Section 9: for a state sigma on E and a weak injective morphism i : E -> F, the cyclic connecting class
vanishes if sigma extends (Theorem 9.1), and "the coboundary of a state is zero iff it extends to a signed state" (Section 10). Section 10:
order cohomology with ordered coefficients replaces kernels by precones; H^1_<=(E) is the monoid of additive maps E -> R>=0
(Section 10), and sigma extends iff sigma lies in the precone of d : H^1_<=(E) -> H^2_<=(F, E) (Theorem 10.5), which by Proposition 10.4
is the image of restriction from H^1_<=(F).

Here E is generated by the windows' outcome events, F = P(X) with X = {0,1}^3 (classical realizability), and i sends an event of a window
to its cylinder set in X.

  RO1 the cyclic test (a signed additive extension to P(X)) passes for every compatible family, contextual or not: false positives on the
      liar cycle and on the noisy liar, as Roumen notes
  RO2 the order-cohomology test, computed literally: an element of H^1_<=(P(X)) (a map d : P(X) -> R>=0 with d(a u b) = d(a) + d(b) for
      disjoint a, b) whose restriction along i is sigma. It exists iff lambda* = 1, on the noisy-liar grid q in [0, 1]: it fails for
      q < 2/3 and holds from q = 2/3, exactly where the Bell value 3 - 1.5 q reaches 2
  RO3 by Proposition 10.4 the literal test is the feasibility LP of the marginal problem (a positive measure on X with the given window
      marginals): the two agree on 200 random compatible families (gluing and non-gluing)
  CA1 whole-record injection is a soft intervention: in the causal model E -> X (provenance E in {genuine, injected}; X | E = genuine
      ~ P, X | E = injected ~ Q), replacing E's mechanism delta_genuine by Bernoulli(eps) yields exactly P_eps on every window
  CA2 per-window injection is not one causal model: different eps (or Q) per window can make the windows fail to glue (lambda* < 1),
      which a single intervention never does (lambda* = 1)
"""
import itertools, os, sys
import numpy as np
from scipy.optimize import linprog
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pce.lab import law
from pce import injection as IJ
from pce import sources as SR
from pce import Window
from pce.integrate import gluable_fraction

rng = np.random.default_rng(20261029); results = []
def check(name, cond, info=""):
    results.append(bool(cond)); print(("PASS " if cond else "FAIL ") + name + (f"   [{info}]" if info else ""), flush=True)

X = list(itertools.product((0, 1), repeat=3)); NX = len(X); WIN = [(0, 1), (1, 2), (0, 2)]; D3 = {"A": 2, "B": 2, "C": 2}
names = {(0, 1): ("A", "B"), (1, 2): ("B", "C"), (0, 2): ("A", "C")}

def events(tables):
    """the effects of E: every subset of every window's four outcomes, with sigma = its table mass and i = its cylinder set in X"""
    out = []
    for w, T in zip(WIN, tables):
        cells = list(itertools.product((0, 1), repeat=2))
        for k in range(1, 5):
            for sub in itertools.combinations(cells, k):
                cyl = frozenset(j for j, x in enumerate(X) if (x[w[0]], x[w[1]]) in sub); out.append((cyl, float(sum(T[c] for c in sub))))
    return out

def cyclic_test(tables):
    """a signed measure psi on X with psi(i(e)) = sigma(e) for all effects e (signed extension); returns the least-squares residual"""
    ev = events(tables); A = np.array([[1.0 if j in cyl else 0.0 for j in range(NX)] for cyl, _ in ev]); b = np.array([s for _, s in ev])
    A = np.vstack([A, np.ones(NX)]); b = np.r_[b, 1.0]; z = np.linalg.lstsq(A, b, rcond=None)[0]; return float(np.abs(A @ z - b).max())

SUBSETS = [frozenset(s) for k in range(NX + 1) for s in itertools.combinations(range(NX), k)]; IDX = {s: k for k, s in enumerate(SUBSETS)}
DISJ = [(a, b) for a in SUBSETS for b in SUBSETS if a and b and not (a & b) and IDX[a] < IDX[b]]

def order_test(tables):
    """literal: d : P(X) -> R>=0 additive on disjoint pairs, d(i(e)) = sigma(e), d(X) = 1 (an element of H^1_<= restricting to sigma)"""
    n = len(SUBSETS); rows = []; rhs = []
    for a, b in DISJ:
        r = np.zeros(n); r[IDX[a | b]] = 1; r[IDX[a]] -= 1; r[IDX[b]] -= 1; rows.append(r); rhs.append(0.0)
    r = np.zeros(n); r[IDX[frozenset()]] = 1; rows.append(r); rhs.append(0.0)
    for cyl, sg in events(tables):
        r = np.zeros(n); r[IDX[cyl]] = 1; rows.append(r); rhs.append(sg)
    res = linprog(np.zeros(n), A_eq=np.array(rows), b_eq=np.array(rhs), bounds=[(0, None)] * n, method="highs")
    return res.status == 0

def lp_test(tables):
    """the marginal-problem LP: a positive measure on X with the window marginals"""
    rows = []; rhs = []
    for w, T in zip(WIN, tables):
        for c in itertools.product((0, 1), repeat=2):
            rows.append([1.0 if (x[w[0]], x[w[1]]) == c else 0.0 for x in X]); rhs.append(float(T[c]))
    res = linprog(np.zeros(NX), A_eq=np.array(rows), b_eq=np.array(rhs), bounds=[(0, None)] * NX, method="highs"); return res.status == 0

eq = np.array([[0.5, 0], [0, 0.5]]); ne = np.array([[0, 0.5], [0.5, 0]])
def noisy(q):
    mix = lambda T: (1 - q) * T + q * np.full((2, 2), 0.25); return [mix(eq), mix(eq), mix(ne)]

# RO1, RO2
qs = np.round(np.linspace(0, 1, 31), 6); rows = []
for q in list(qs) + [2 / 3 - 1e-3, 2 / 3, 2 / 3 + 1e-3]:
    T = noisy(q); lam = gluable_fraction(D3, [Window(names[w], t) for w, t in zip(WIN, T)]).lam
    rows.append((q, cyclic_test(T), order_test(T), lam > 1 - 1e-7))
cyc_ok = all(r[1] < 1e-10 for r in rows)
ord_ok = all(r[2] == r[3] for r in rows) and all((not r[2]) == (r[0] < 2 / 3 - 1e-9) for r in rows)
check("RO1 the cyclic (signed) test passes on every compatible family: false positives on the liar and the noisy liar", cyc_ok,
      f"max residual {max(r[1] for r in rows):.1e} over {len(rows)} values of q")
check("RO2 the order-cohomology test (literal H^1_<= of P(X), restricted along i) fails exactly for q < 2/3 and agrees with lambda* = 1 everywhere",
      ord_ok, f"fails at q = {[round(r[0], 3) for r in rows if not r[2]][:3]}...; first pass at q = {min(r[0] for r in rows if r[2]):.4f}")

# RO3
agree = 0; n_glue = 0
for _ in range(200):
    if rng.random() < 0.5:
        P = IJ.as_law(rng.dirichlet(np.ones(8)), 3); T = [P.sum(axis=2), P.sum(axis=0), P.sum(axis=1)]
    else:                                                            # a compatible family that may not glue: mix a law with the liar cycle
        P = IJ.as_law(rng.dirichlet(np.ones(8)), 3); t = rng.uniform(0, 1); T = [(1 - t) * P.sum(axis=2) + t * eq, (1 - t) * P.sum(axis=0) + t * eq, (1 - t) * P.sum(axis=1) + t * ne]
    o, l = order_test(T), lp_test(T); agree += (o == l); n_glue += l
check("RO3 the literal order-cohomology test equals the marginal-problem LP (Proposition 10.4) on 200 random compatible families", agree == 200,
      f"{n_glue} of 200 glue")

# CA1
P = law(0.6, np.array([.5, .1, .4]), np.array([.05, .5, .1])); Q = SR.hidden_Q(P, 0.027); ok = True
for eps in (0.0, 0.03, 0.05, 0.2):
    joint = np.stack([(1 - eps) * P, eps * Q])                      # the law of (E, X) after the soft intervention on E
    obs = joint.sum(axis=0); ok &= np.allclose(obs, IJ.mix(P, Q, eps))
    for w in WIN:
        ok &= np.allclose(obs.sum(axis=tuple(i for i in range(3) if i not in w)), IJ.mix(P, Q, eps).sum(axis=tuple(i for i in range(3) if i not in w)))
check("CA1 whole-record injection = a soft intervention on the provenance node of E -> X: the observed law is P_eps on every window", ok)

# CA2
Qv = np.zeros((2, 2, 2)); Qv[1, 1, 1] = 1.0
Tw = [IJ.mix(P, Qv, 0.3).sum(axis=2), P.sum(axis=0), P.sum(axis=1)]          # injection into the AB window only
lam_w = gluable_fraction(D3, [Window(names[w], t) for w, t in zip(WIN, Tw)]).lam
lam_1 = gluable_fraction(D3, [Window(names[w], IJ.mix(P, Qv, 0.3).sum(axis=tuple(i for i in range(3) if i not in w))) for w in WIN]).lam
check("CA2 per-window injection is not one causal model: injecting into AB alone breaks gluing (lambda* < 1); one intervention keeps lambda* = 1",
      lam_w < 1 - 1e-6 and lam_1 > 1 - 1e-9, f"per-window lambda* {lam_w:.3f}; single intervention {lam_1:.3f}")

print(f"{sum(results)}/{len(results)} passed")
