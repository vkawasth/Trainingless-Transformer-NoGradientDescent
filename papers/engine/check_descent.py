def toric_ideal(m):
    v = sp.symbols(f"v0:{m}"); E = list(itertools.combinations(range(m), 2)); Ms = sp.symbols(" ".join(f"M{i}{j}" for i, j in E))
    G = sp.groebner([Ms[k] - v[i] * v[j] for k, (i, j) in enumerate(E)], *v, *Ms, order="lex")
    return [g for g in G.exprs if not g.free_symbols & set(v)], Ms
