"""check_descent.py -- the descent tower (lab paper, Proposition "spectrum and descent" and Theorem M).

  DC1 level 0, algebraic: on the pair cover (m = 3, 4) and the triple cover (m = 4) the marginal map from signed global laws onto the
      algebraic limit (consistent signed families, ker d^0) is surjective, and its kernel is spanned exactly by the Walsh characters of the
      sets contained in no window (dimensions 1, 5 and 1)
  DC2 level 0, linear Cech cohomology of the presheaf of signed measures vanishes in degrees 1 and up on these covers: nothing obstructs
      descent algebraically
  DC3 level 0, real points: the family A = B, B = C, A != C (uniform singles) is consistent (zero energy), has a signed global extension,
      and no part of it glues (lambda* = 0: strongly contextual; least negative mass nu* = 1/2): the obstruction is positivity only, certified by the LP witness
  DC4 level 1, kernel: over Z/2 the unsigned coboundary has kernel Z/2 on every connected graph (the label switch v -> -v); over R its
      kernel is 0 on the triangle and K4 (non-bipartite) and 1-dimensional on the path AB, BC (bipartite: |v| is not pinned)
  DC5 level 1, sign: on the triangle the Z/2 class of the sign cochain is sign(M_01 M_02 M_12) = sign(Delta_m) (200 random laws)
  DC6 level 1, modulus: coker of the unsigned incidence over R has dimension 0 on the triangle and 2 on K4, spanned by the two log tetrad
      ratios; the class vanishes on two-type laws and not on random laws
  DC7 the toric ideal: the ideal of the image of v -> (v_i v_j) is 0 on the triangle and generated by the two tetrads on K4 (Groebner
      elimination)
  DC8 real sign cosets: of the 2^E sign patterns, exactly 2^(m - 1) come from real v; the cosets are counted by H^1(G; Z/2): 2 on the
      triangle, 8 on K4
  DC9 realizability: on three variables, pair tables have a two-type explanation iff the sign class is 0 and the walls leave a segment
      (the modulus class is always 0); every two-type truth passes (300 random laws)
  DC10 level 2: a two-type law at m = 4 has delta r = 0 on the triple cover; a single-triple channel chi_S leaves levels 0 and 1 unchanged
      (same pair tables) and makes delta r non-zero at first order: the obstruction moves up exactly one level
  DC11 the fibre: at m = 3 the line of laws with the observed pair tables (level 0) meets the level-2 condition (rhat inside the walls)
      exactly in the hiding segment
  DC12 labels: the obstruction for source-labelled batches is the coboundary delta m_T on the complete nerve (degree 0, not an H^1
      class); its energy is K (between-source + within-source), the coarse and fine covers of the gluing filter
  DC13 the image diagram forgets the obstruction: every 2x2 table is a two-type mixture on its own, and a law with Delta_m < 0 has gluing
      pair tables that admit no global two-type realization; only the realization diagram (with its Z/2) sees it
  DC14 the three cases: incongruence (the worked example's conflicting trials: energy > 0, lambda* = 0.86), contextuality (the liar
      cycle: energy 0, lambda* = 0, maximal violation of P(A=B) + P(B=C) + P(A!=C) <= 2), gluing (any consistent tables on a tree cover)
  DC15 any connected pattern of observed pairs: the number of two-type model equations (the codimension of the image of v -> v_i v_j,
      from the Jacobian) is E - rank B, and the sign conditions number b1 = E - m + 1 (60 random graphs, m = 3..7)
  DC16 strictness: every stage of the tower has a witness passing all earlier stages and failing there
  DC17 normalisation: the unnormalised cosimplicial (comonadic) Cech complex, all ordered tuples with repetitions, has the same
      cohomology as the alternating complex (7, 0, 0 on the pair cover)
"""
