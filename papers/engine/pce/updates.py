"""Non-commuting updates tracked by the conservation of probability mass.

Laws are arrays over a finite product space; every update below preserves total mass 1 and positivity.
  likelihood(p, L)              Bayes / virtual evidence: p -> L p / <L, p> (a diagonal reweighting). The mass factor <L, p> is the evidence.
  jeffrey(p, axes, q)           Jeffrey's rule on the partition generated by the variables `axes`, with new marginal q:
                                p -> sum_i q_i p(. | B_i). It is the I-projection of p onto {p' : p'_axes = q}, and a likelihood update with
                                the state-dependent ratio q_i / p(B_i) on block B_i.
  field(p, axes, beta)          the same update specified by Bayes factors beta_i instead of target marginals (Field's rule): a likelihood
                                update with L = beta on B_i, hence commutative
  two_orders(p, A, q, C, r)     both orders of two Jeffrey updates, and the holonomy h = log(J_C J_A p / J_A J_C p) (up to a constant),
                                which depends only on the (A, C) cell: h_ij = log b_j - log a_i, a_i = (J_C p)(A_i) / p(A_i),
                                b_j = (J_A p)(C_j) / p(C_j)
  moved(p, p2)                  mass moved = TV(p, p2)
  cycle(p, windows, rounds)     cyclic Jeffrey updating on windows [(axes, table)]: the mass moved by every update and every round
  odds(p, axes_a, axes_c)       the cross-ratios of the (A, C) cell-mass table: invariant under every Jeffrey or likelihood update on A or C
  curvature(K12, K23, K13)      for linear transports (Markov kernels, column-stochastic): K13 - K23 K12, a mass-neutral operator
"""
from __future__ import annotations
import itertools
import numpy as np


def _blocks(shape, axes):
    """index of the block (cell of the variables in `axes`) of every atom, and the number of blocks."""
    sub = [shape[a] for a in axes]; idx = np.zeros(shape, int)
    for a in itertools.product(*[range(s) for s in shape]):
        idx[a] = np.ravel_multi_index(tuple(a[k] for k in axes), sub)
    return idx, int(np.prod(sub))


def marg(p, axes):
    p = np.asarray(p, float); keep = tuple(axes)
    return p.sum(axis=tuple(i for i in range(p.ndim) if i not in keep)).transpose(np.argsort(np.argsort(keep)))


def likelihood(p, L):
    x = np.asarray(p, float) * L; m = x.sum(); return x / m, m


def jeffrey(p, axes, q):
    p = np.asarray(p, float); idx, nb = _blocks(p.shape, axes)
    pb = np.bincount(idx.ravel(), weights=p.ravel(), minlength=nb); qb = np.asarray(q, float).ravel()
    ratio = np.where(pb > 0, qb / np.where(pb > 0, pb, 1), 0.0)
    return p * ratio[idx]


def field(p, axes, beta):
    p = np.asarray(p, float); idx, nb = _blocks(p.shape, axes)
    return likelihood(p, np.asarray(beta, float).ravel()[idx])[0]


def moved(p, p2):
    return 0.5 * float(np.abs(np.asarray(p) - np.asarray(p2)).sum())


def two_orders(p, A, q, C, r):
    x, y = jeffrey(p, C, r), jeffrey(p, A, q)
    pAC, pCA = jeffrey(x, A, q), jeffrey(y, C, r)                         # A after C, and C after A
    a = marg(x, A).ravel() / marg(p, A).ravel(); b = marg(y, C).ravel() / marg(p, C).ravel()
    iA, _ = _blocks(np.shape(p), A); iC, _ = _blocks(np.shape(p), C)
    h_pred = np.log(b)[iC] - np.log(a)[iA]
    with np.errstate(divide="ignore", invalid="ignore"): h = np.log(pAC / pCA)
    return {"A_after_C": pAC, "C_after_A": pCA, "a": a, "b": b, "h": h, "h_pred": h_pred, "order_gap": moved(pAC, pCA)}


def cycle(p, windows, rounds=50):
    steps, laws = [], [np.asarray(p, float)]
    for _ in range(rounds):
        for axes, t in windows:
            new = jeffrey(laws[-1], axes, t); steps.append(moved(laws[-1], new)); laws.append(new)
    n = len(windows); per_round = [sum(steps[k:k + n]) for k in range(0, len(steps), n)]
    return {"steps": steps, "per_round": per_round, "law": laws[-1], "laws": laws}


def odds(p, A, C):
    M = np.asarray(marg(p, tuple(A) + tuple(C)), float).reshape(int(np.prod([np.shape(p)[a] for a in A])), -1)
    out = []
    for i, k in itertools.combinations(range(M.shape[0]), 2):
        for j, l in itertools.combinations(range(M.shape[1]), 2):
            out.append(np.log(M[i, j] * M[k, l] / (M[i, l] * M[k, j])))
    return np.array(out)


def curvature(K12, K23, K13):
    return np.asarray(K13) - np.asarray(K23) @ np.asarray(K12)
