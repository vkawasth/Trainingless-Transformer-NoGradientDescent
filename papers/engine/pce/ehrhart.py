"""The ring of contingency tables and the decision on the hiding segment (Gap 3; lab paper Section "Theorem D", companion "Coupling
algebras", Section 7). Three binary variables, utilities on all three.

The pair tables of a 2x2x2 law fix it up to the single move chi(x) = prod_i (2 x_i - 1) (the no-three-way-interaction model: its toric
ideal is principal, generated by one quartic binomial). Moving a law along chi by eps moves its centred triple moment by exactly eps,
because sum_x chi(x) prod_i (x_i - mu_i) = prod_i ((1 - mu_i) + mu_i) = 1.

  CHI, X                       the move and the cells
  fibre_int(T0)                integer range [jlo, jhi] of j with T0 + j chi >= 0 (T0 an integer table)
  count_fibre(T0)              jhi - jlo + 1
  lattice_in(n, m0, I)         integer j with m0 + j / n in the closed interval I (the lattice points of the dilated sub-segment)
  walsh(u)                     c = sum_x u(x) chi(x): the slope of E[u] in the triple moment (beta = v_T c in r)
  tropical(vals, s)            -(1/s) log sum exp(-s vals): the weighted count whose s -> infinity limit is the minimum
  conti_traverso(T, c)         normal form of T for the binomial oriented by the cost c (move against the cost while feasible)
  worst_lp(P, u)               min of E[u] over all real laws with the pair tables of P (scipy linprog), and the binding cell
  psi_of(P)                    the three-way log odds ratio sum_x chi(x) log P(x)
  eps_of_psi(P, psi)           the point P + eps chi of the margin fibre of P with that log odds ratio (bisection; monotone)
  cond_pmf(T, psi)             conditional law of j given the pair tables of T: proportional to exp(psi j) / prod_x (T + j chi)_x!
  exact_ci(T, alpha)           two-sided exact conditional interval for psi (inversion of the two one-sided tests)
  tau_c(P, vT), tau_m(P, vT)   asymptotic sd of the triple-window estimate of r: conditional (efficient along the fibre, 1/sqrt K) and
                               the plug-in centred moment (sd of its influence function); tau_c <= tau_m by Cramer-Rao
"""
from __future__ import annotations
import itertools
import numpy as np
from scipy.special import gammaln, logsumexp

X = list(itertools.product((0, 1), repeat=3))
CHI = np.zeros((2, 2, 2))
for _x in X: CHI[_x] = np.prod([2 * a - 1 for a in _x])


def fibre_int(T0):
    T0 = np.asarray(T0)
    jlo = max(-int(T0[x]) for x in X if CHI[x] > 0); jhi = min(int(T0[x]) for x in X if CHI[x] < 0)
    return jlo, jhi


def count_fibre(T0):
    lo, hi = fibre_int(T0); return max(0, hi - lo + 1)


def lattice_in(n, m0, I):
    lo, hi = I; return int(np.floor(n * (hi - m0) + 1e-12)) - int(np.ceil(n * (lo - m0) - 1e-12)) + 1


def walsh(u):
    return float(sum(u(x) * CHI[x] for x in X))


def tropical(vals, s):
    vals = np.asarray(vals, float); return float(-logsumexp(-s * vals) / s)


def conti_traverso(T, c):
    """reduce the table T by the single Groebner binomial, oriented so that the leading term is the costlier side: apply -sign(c) chi
    while the table stays nonnegative. Returns the normal form (the minimiser of the linear cost c * j on the fibre) and the steps"""
    T = np.array(T, dtype=object if isinstance(np.asarray(T).flat[0], (int, np.integer)) else float); d = -np.sign(c) * CHI; steps = 0
    if c == 0: return T, 0
    while all(T[x] + d[x] >= 0 for x in X):
        T = T + d; steps += 1
    return T, steps


def pair_constraints():
    """the 0/1 matrix of the pair margins (12 rows: three 2x2 tables) acting on the 8 cells"""
    rows = []
    for (i, j) in itertools.combinations(range(3), 2):
        for a, b in itertools.product((0, 1), repeat=2):
            rows.append([1.0 if (x[i] == a and x[j] == b) else 0.0 for x in X])
    return np.array(rows)


def worst_lp(P, u):
    from scipy.optimize import linprog
    A = pair_constraints(); b = A @ np.array([P[x] for x in X]); cost = np.array([u(x) for x in X])
    res = linprog(cost, A_eq=A, b_eq=b, bounds=[(0, None)] * 8, method="highs")
    z = res.x; zero = [k for k in range(8) if z[k] < 1e-10]
    return float(res.fun), zero


def psi_of(P):
    return float(sum(CHI[x] * np.log(P[x]) for x in X))


def eps_range(P):
    return max(-P[x] for x in X if CHI[x] > 0), min(P[x] for x in X if CHI[x] < 0)


_CV = np.array([CHI[x] for x in X])


def eps_of_psi(P, psi, tol=1e-13):
    """safeguarded Newton (psi is increasing in eps, with derivative sum_x 1 / (P_x + eps chi_x))"""
    p = np.array([P[x] for x in X]); a, b = eps_range(P); e = 0.5 * (a + b)
    for _ in range(200):
        q = p + e * _CV; f = float(_CV @ np.log(q)) - psi
        if f < 0: a = e
        else: b = e
        en = e - f / float(np.sum(1.0 / q))
        if not (a < en < b): en = 0.5 * (a + b)
        if abs(en - e) < tol * max(1.0, abs(e)) or b - a < tol: return en
        e = en
    return e


def cond_logw(T, window=None):
    """log weights of j in [jlo, jhi] (psi = 0): -sum_x log (T + j chi)_x!; window = (a, b) restricts j to [a, b]"""
    jlo, jhi = fibre_int(T)
    if window is not None: jlo, jhi = max(jlo, window[0]), min(jhi, window[1])
    js = np.arange(jlo, jhi + 1)
    lw = -sum(gammaln(np.asarray(T)[x] + js * CHI[x] + 1) for x in X); return js, lw


def cond_pmf(T, psi):
    js, lw = cond_logw(T); a = lw + psi * js; return js, np.exp(a - logsumexp(a))


def _tail(js, lw, psi, j0, upper):
    a = lw + psi * js; L = logsumexp(a); mask = js >= j0 if upper else js <= j0
    return float(np.exp(logsumexp(a[mask]) - L)) if mask.any() else 0.0


def exact_ci(T, alpha=0.05, j_obs=0):
    """two-sided exact interval for psi given the pair tables of T and the observed position j_obs (0 = T itself):
    psi_L solves P_psi(J >= j_obs) = alpha / 2, psi_U solves P_psi(J <= j_obs) = alpha / 2; infinite at the fibre's ends.
    Brent root-finding inside a bracket of +- 40 standard errors around the (Haldane-corrected) log odds ratio of T + j_obs chi."""
    Tj = np.asarray(T, float) + j_obs * CHI; jlo, jhi = fibre_int(T)
    ph = float(sum(CHI[x] * np.log(Tj[x] + 0.5) for x in X)); se = float(np.sqrt(sum(1.0 / (Tj[x] + 0.5) for x in X)))
    W = int(np.ceil(120 / se)) + 10; js, lw = cond_logw(T, (j_obs - W, j_obs + W))   # the bracket moves the mean of j by <= 40 / se
    def solve(upper):
        if (upper and j_obs == jlo) or ((not upper) and j_obs == jhi): return -np.inf if upper else np.inf
        from scipy.optimize import brentq                            # the tail is increasing in psi when upper, decreasing otherwise
        g = lambda m: np.log(max(_tail(js, lw, m, j_obs, upper), 1e-300)) - np.log(alpha / 2)
        return brentq(g, ph - 40 * se, ph + 40 * se, xtol=1e-10)
    return solve(True), solve(False)


def tau_c(P, vT):
    K = sum(1.0 / P[x] for x in X); return float(1.0 / (abs(vT) * np.sqrt(K)))


def tau_m(P, vT):
    mu = [sum(P[x] * x[i] for x in X) for i in range(3)]; mS = sum(P[x] * np.prod([x[i] - mu[i] for i in range(3)]) for x in X)
    M = {(i, j): sum(P[x] * (x[i] - mu[i]) * (x[j] - mu[j]) for x in X) for i, j in itertools.combinations(range(3), 2)}
    oth = ((1, 2), (0, 2), (0, 1))
    IF = lambda x: np.prod([x[i] - mu[i] for i in range(3)]) - mS - sum(M[oth[i]] * (x[i] - mu[i]) for i in range(3))
    return float(np.sqrt(sum(P[x] * IF(x) ** 2 for x in X)) / abs(vT))


def m_hat(T):
    """centred triple moment of a count table with its own means"""
    n = T.sum(); Q = T / n; mu = [sum(Q[x] * x[i] for x in X) for i in range(3)]
    return float(sum(Q[x] * np.prod([x[i] - mu[i] for i in range(3)]) for x in X))
