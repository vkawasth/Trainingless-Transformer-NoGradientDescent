"""Quantum graded gluing as the positivity domain of a hereditary quadratic matrix polynomial (Islam, Volcic, Woerdeman 2026).

Windows w are sets of qubits with density matrices rho_w. A global unnormalised vector psi is an alpha-explanation of mass |psi|^2 when
Tr_rest(psi psi^*) <= rho_w (Loewner) for every window: the quantum form of alpha q|_w <= t_w. For one window, reorder psi as
psi_{a k} (a = window index, k = the rest) and let K = sum_{a,k} |k><a| x_{ak}; then K^* K evaluated at psi is Tr_rest(psi psi^*)^T, and
  f_w = rho_w^T - K^* K
is a self-adjoint hereditary quadratic with constant term rho_w^T, no linear term, and f_w(psi) >= 0  <=>  Tr_rest(psi psi^*) <= rho_w.
The family gives f = (+)_w f_w and the explanation set is the positivity domain D(f); level n evaluates f at tuples X_{ak} in M_n.

  ptrace(S, keep, m)                 reduced operator of an m-qubit operator S on the qubits in keep (in increasing order)
  Kcoeffs(keep, m)                   the coefficient matrices K_j (one per variable x_j = psi_j) of K for a window
  f_eval(rho_w, keep, m, X)          f_w at level n: X has shape (2^m, n, n) (X[j] is the matrix substituted for x_j); n = 1 for vectors
  linearisation(rho_w, keep, m)      the pencil L_f = [[I, K], [K^*, rho_w^T]] as (constant, [A_j], [A_j^*])
  algebra_dim(mats)                  dimension of the unital algebra generated by a set of matrices (Burnside: full iff = size^2)
  lam_pure(windows, m)               max |psi|^2 over D_1(f) (pure, level 1), by multi-start optimisation of the radial function
  lam_mixed(windows, m)              max tr sigma over sigma >= 0 with Tr_rest sigma <= rho_w (a semidefinite program)
  radial(windows, m, u)              the largest s with s * u in the domain, for a unit vector u (closed form per window)
"""
from __future__ import annotations
import itertools
import numpy as np


def ptrace(S, keep, m):
    keep = sorted(keep); rest = [q for q in range(m) if q not in keep]
    T = S.reshape([2] * (2 * m)); perm = keep + rest; T = T.transpose(perm + [p + m for p in perm])
    dk, dr = 2 ** len(keep), 2 ** len(rest); T = T.reshape(dk, dr, dk, dr)
    return np.einsum("arbr->ab", T)


def _reorder(m, keep):
    keep = sorted(keep); rest = [q for q in range(m) if q not in keep]
    idx = np.arange(2 ** m).reshape([2] * m).transpose(keep + rest).reshape(-1)
    return idx, 2 ** len(keep), 2 ** len(rest)          # psi reordered = psi[idx], shaped (dk, dr)


def Kcoeffs(keep, m):
    idx, dk, dr = _reorder(m, keep); Ks = []
    pos = {int(j): t for t, j in enumerate(idx)}
    for j in range(2 ** m):
        a, k = divmod(pos[j], dr); M = np.zeros((dr, dk), complex); M[k, a] = 1.0; Ks.append(M)
    return Ks


def f_eval(rho_w, keep, m, X):
    """X: (2^m, n, n) complex; returns the (dk n) x (dk n) matrix f_w(X) = rho_w^T (x) I_n - K(X)^* K(X)."""
    Ks = Kcoeffs(keep, m); n = X.shape[1]
    KX = sum(np.kron(Kj, X[j]) for j, Kj in enumerate(Ks))
    return np.kron(rho_w.T, np.eye(n)) - KX.conj().T @ KX


def linearisation(rho_w, keep, m):
    Ks = Kcoeffs(keep, m); dr, dk = Ks[0].shape; s = dr + dk
    C0 = np.zeros((s, s), complex); C0[:dr, :dr] = np.eye(dr); C0[dr:, dr:] = rho_w.T
    A = []; Astar = []
    for Kj in Ks:
        M = np.zeros((s, s), complex); M[:dr, dr:] = Kj; A.append(M)          # coefficient of x_j
        Ms = np.zeros((s, s), complex); Ms[dr:, :dr] = Kj.conj().T; Astar.append(Ms)   # coefficient of y_j = x_j^*
    return C0, A, Astar


def algebra_dim(mats, tol=1e-9, max_words=6):
    d = mats[0].shape[0]; basis = []
    def add(M):
        v = M.reshape(-1)
        if basis:
            B = np.array(basis).T; c, *_ = np.linalg.lstsq(B, v, rcond=None); r = v - B @ c
        else: r = v
        if np.linalg.norm(r) > tol * max(1.0, np.linalg.norm(v)): basis.append(r / np.linalg.norm(r)); return True
        return False
    add(np.eye(d)); frontier = [np.eye(d)]
    for _ in range(max_words):
        new = []
        for W in frontier:
            for M in mats:
                P = W @ M
                if add(P): new.append(P)
        if not new or len(basis) == d * d: break
        frontier = new
    return len(basis)


def radial(windows, m, u):
    """largest s >= 0 with s * u in the positivity domain: s^2 = min_w 1 / lambda_max(rho_w^{-1/2} Tr_rest(u u^*) rho_w^{-1/2})."""
    P = np.outer(u, u.conj()); best = np.inf
    for keep, rho in windows:
        v, U = np.linalg.eigh(rho); R = U @ np.diag(v ** -0.5) @ U.conj().T
        lm = np.linalg.eigvalsh(R @ ptrace(P, keep, m) @ R)[-1]; best = min(best, 1 / lm)
    return best


def lam_pure(windows, m, starts=40, seed=0, return_all=False):
    from scipy.optimize import minimize
    rng = np.random.default_rng(seed); D = 2 ** m; outs = []
    def neg(z):
        u = z[:D] + 1j * z[D:]; u = u / np.linalg.norm(u); return -radial(windows, m, u)
    for _ in range(starts):
        z0 = rng.normal(size=2 * D); r = minimize(neg, z0, method="Nelder-Mead", options={"maxiter": 6000, "xatol": 1e-9, "fatol": 1e-12})
        r = minimize(neg, r.x, method="Powell", options={"maxiter": 20000, "xtol": 1e-10, "ftol": 1e-13})
        u = r.x[:D] + 1j * r.x[D:]; outs.append((-r.fun, u / np.linalg.norm(u)))
    best = max(o[0] for o in outs)
    return (best, outs) if return_all else best


def lam_mixed(windows, m):
    import cvxpy as cp
    D = 2 ** m; S = cp.Variable((D, D), hermitian=True); cons = [S >> 0]
    for keep, rho in windows:
        rest = [q for q in range(m) if q not in keep]; T = S; dims = [2] * m
        for q in sorted(rest, reverse=True):
            T = cp.partial_trace(T, dims, axis=q); dims = dims[:q] + dims[q + 1:]
        cons.append(rho - T >> 0)
    prob = cp.Problem(cp.Maximize(cp.real(cp.trace(S))), cons); prob.solve(solver="SCS", eps=1e-9, max_iters=200000)
    return float(prob.value), S.value


def _window_ops(windows, m):
    ops = []
    for keep, rho in windows:
        idx, dk, dr = _reorder(m, keep); v, U = np.linalg.eigh(rho); R = U @ np.diag(v ** -0.5) @ U.conj().T; ops.append((idx, dk, dr, R))
    return ops


def _lams(ops, u):
    """for each window: lambda_max of R Tr_rest(u u^*) R and its gradient direction (d lambda / d conj(u))."""
    out = []
    for idx, dk, dr, R in ops:
        Psi = u[idx].reshape(dk, dr); M = R @ Psi @ Psi.conj().T @ R; w, V = np.linalg.eigh(M); v = V[:, -1]
        g = np.zeros_like(u); g[idx] = (R @ np.outer(v, v.conj()) @ R @ Psi).reshape(-1); out.append((w[-1], g))
    return out


def ascend(windows, m, u0, iters=3000, beta=200.0, lr=0.05):
    """projected gradient descent on the unit sphere of the smooth maximum (1/beta) log sum exp(beta lambda_w); returns (radial^2, u)."""
    ops = _window_ops(windows, m); u = u0 / np.linalg.norm(u0)
    for k in range(iters):
        L = _lams(ops, u); lam = np.array([l for l, _ in L]); wts = np.exp(beta * (lam - lam.max())); wts /= wts.sum()
        g = sum(wt * gg for wt, (_, gg) in zip(wts, L)); g = g - np.vdot(u, g) * u
        u = u - lr * g / max(lam.max(), 1e-12); u /= np.linalg.norm(u)
    lam = max(l for l, _ in _lams(ops, u)); return 1.0 / lam, u


def lam_pure_fast(windows, m, starts=60, seed=0, return_all=False, iters=3000):
    rng = np.random.default_rng(seed); D = 2 ** m; outs = []
    for _ in range(starts):
        u0 = rng.normal(size=D) + 1j * rng.normal(size=D); outs.append(ascend(windows, m, u0, iters=iters))
    best = max(o[0] for o in outs)
    return (best, outs) if return_all else best


def modes(outs, tol=1e-4, overlap=0.995):
    """distinct local maxima (up to global phase) among optimisation outputs"""
    outs = sorted(outs, key=lambda o: -o[0]); md = []
    for v, u in outs:
        if all(abs(np.vdot(u, w)) < overlap for _, w in md): md.append((v, u))
    return md
