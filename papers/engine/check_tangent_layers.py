def rand_law(n, zeros=0):
    p = rng.integers(1, 9, size=n).astype(float)
    if zeros: p[rng.choice(n, zeros, replace=False)] = 0
    return p / p.sum()

def rand_T2(x): return TLM.rand_T2_blocks(x, [np.arange(len(x))], rng)

