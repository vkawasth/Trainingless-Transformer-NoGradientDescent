def bayes_dec_derivative(w, ps, a, us, Am):
    """reweighting + within-source parts of D[C_A mu]"""
    pA = np.array([(Am * p).sum() for p in ps]); uA = np.array([(Am * u).sum() for u in us]); Z = (w * pA).sum()
    piA = w * pA / Z; dnum = a * pA + w * uA; dpiA = dnum / Z - piA * dnum.sum() / Z
    rew = sum(dpiA[i] * TLM.cond_vec(ps[i], Am) for i in range(len(ps)))
    within = sum(piA[i] * TLM.dcond(ps[i], Am, us[i]) for i in range(len(ps)))
    return rew, within
