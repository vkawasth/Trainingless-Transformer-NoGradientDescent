def pool_f(nsrc, nx):
    def f(X):
        w = [X[i] for i in range(nsrc)]; ps = [[X[nsrc + i * nx + x] for x in range(nx)] for i in range(nsrc)]
        return [sum((w[i] * ps[i][x] for i in range(1, nsrc)), w[0] * ps[0][x]) for x in range(nx)]
    return f
def blocks_for(nsrc, nx): return [np.arange(nsrc)] + [nsrc + i * nx + np.arange(nx) for i in range(nsrc)]
