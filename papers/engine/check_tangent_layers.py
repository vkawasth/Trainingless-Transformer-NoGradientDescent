"""Checks for Step 2 of "Probability, Context and Differentiation: The Layers": the cone tangent structure T through the layers.
  TL1  T and the provenance comonad: for discrete L, T(L x Delta) = L x T Delta; T lam maps T^2 Delta_X into T^2 Delta_{L x X}, and the
       counit and comultiplication axioms of the distributive law hold coefficient by coefficient on T^2 points (the maps are linear)
  TL2  lam is a face embedding: D lam is injective with image the zero-sum directions on row l; a feasible direction at delta_l (x) p is
       tangent to the face iff it puts no mass on other labels; otherwise u = D lam(v) + m (Q' - q) with v in C_p, m > 0 and Q' a law
       on the other labels: a face direction plus a whole-record injection under other labels
  TL3  forgetting provenance (D eps) maps C_q onto C_p; the injected-source direction t(delta_l' (x) Q - delta_l (x) p) and the internal
       shift t delta_l (x) (Q - p) have the same image t(Q - p); the relabelling direction delta_l' (x) p - delta_l (x) p is invisible
  TL4  marginalisation: T M_S maps C_p onto C_{M_S p} (the lift u = v(x_S) p(x | x_S), uniform on empty fibres, is feasible and
       maps to v); its kernel (window-invisible directions) has dimension |X| - |X_S|; T^2 M_S maps T^2 points into T^2 points; D^2 = 0
  TL5  conditioning: DC_A maps C_p onto C_{C_A p} (lift u = p(A) v); kernel {u : N_A u proportional to N_A p} of dimension |X| - |A|;
       the second-order corner criterion holds at laws with zeros, and the direct T^2 test finds no violation (both tests reject a
       negative control, p -> ((p_a - p_b)^2, 1 - (p_a - p_b)^2) at the midpoint); the pole |DC_A| ~ 1/p(A)
  TL6  pooling mu_n(w, p_1..p_n) = sum w_i p_i: the product of feasible cones maps into C_pooled (including w_i = 0 sources); the
       second-order criterion holds, by the case analysis of the paper, at corners with w_i = 0 and with zero cells; direct T^2 test;
       D^3 = 0 (bilinear)
  TL7  the differentiated Bayes decomposition: D[C_A mu](a, u) = sum_l (D pi_l^A) C_A p_l + sum_l pi_l^A DC_A(p_l)[u_l]
       (reweighting + within-source), exactly, on the worked example and at random points
  TL8  the paper's worked example, exactly: f(pi_1) = P(H = 1 | R = 1) has f(1/4) = 9/23, f'(1/4) = -16/529, f''(1/4) = 384/12167;
       the reweighting term alone gives f'; Bayes weight pi_1^A has derivative 640/529; the Taylor remainder is O(h^3)
  TL9  T^k H is the convex cone generated by elementary tensors u_1(e_1)...u_k(e_k), u_i in T H (explicit decomposition, k = 1..4),
       hence closed under the Weil product (exhaustive on a grid for k = 2, sampled for k = 3); so pooling preserves T^3 (direct test)
"""
