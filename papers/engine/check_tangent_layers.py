    a = TLM.rand_feasible(w, rng); us = [TLM.rand_feasible(p, rng) for p in ps]
    pooled = sum(w[i] * ps[i] for i in range(ns)); dpool = sum(a[i] * ps[i] + w[i] * us[i] for i in range(ns))
    rew, within = bayes_dec_derivative(w, ps, a, us, Am); ok &= np.allclose(TLM.dcond(pooled, Am, dpool), rew + within)
