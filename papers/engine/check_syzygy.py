"""check_syzygy.py -- Phase III, Stage 1: relations among the observed moments and their syzygies, for covers by pairs and triples
(companion "Two latent types on arbitrary covers"). Macaulay2 computes generators and minimal free resolutions; everything it reports is
re-derived independently here. Writes lab/syzygy.json.

  SZ1  the generators vanish at 40 random model points of every cover, not at random non-model points; codim I = n - rank A
  SZ2  every multigraded Betti number from Macaulay2 equals dim H~_{i-1}(Delta_b; Q) computed from the configuration (Hochster's formula)
  SZ3  on the bowtie and on C4 + 012 + 123, Hochster's formula finds no Betti number outside Macaulay2's list, for all b = A u, |u| <= 4
  SZ4  the pair part: I cap k[c] is the toric ideal of the incidence matrix B, of codimension |E| - rank B (Phase I's modulus class),
       generated by the binomials of even closed walks (an even cycle; two odd cycles joined by a path, path edges twice)
  SZ5  the triple part: each triple beyond those absorbed by the free scales adds one to the codimension (a second-triple test)
  SZ6  the bowtie is Hilbert-Burch: the three generators are the 2 x 2 minors of [[m012, c01, c02 c12], [m234, c34, c23 c24]] and the
       two syzygies are its rows
  SZ7  syzygies are the dependencies among tests: at a model point the Jacobian of the generators has rank codim I, and its left kernel
       (dimension #gens - codim) is spanned by the first syzygies evaluated there; a coincidence at a vertex shared by windows (the
       bowtie's cut vertex) drops the rank, a coincidence elsewhere does not
  SZ8  all ideals are Cohen-Macaulay here (projective dimension = codimension); the Betti tables are recorded
"""
import itertools, json, os, sys
from collections import Counter
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from pce import syzygy as SZ

rng = np.random.default_rng(20261029); results = []; OUT = {}
def check(name, cond, info=""):
    results.append(bool(cond)); print(("PASS " if cond else "FAIL ") + name + (f"   [{info}]" if info else ""), flush=True)
pairs = lambda Ws: sorted({e for W in Ws for e in itertools.combinations(W, 2)})
COVERS = {
    "K3+012": (3, pairs([(0, 1, 2)]), [(0, 1, 2)]),
    "C4+012": (4, [(0, 1), (1, 2), (2, 3), (0, 3)], [(0, 1, 2)]),
    "C4+012+123": (4, [(0, 1), (1, 2), (2, 3), (0, 3)], [(0, 1, 2), (1, 2, 3)]),
    "K4 pairs": (4, list(itertools.combinations(range(4), 2)), []),
    "bowtie": (5, pairs([(0, 1, 2), (2, 3, 4)]), [(0, 1, 2), (2, 3, 4)]),
    "fan": (5, pairs([(0, 1, 2), (0, 2, 3), (0, 3, 4)]), [(0, 1, 2), (0, 2, 3), (0, 3, 4)]),
    "K4 triples": (4, list(itertools.combinations(range(4), 2)), list(itertools.combinations(range(4), 3))),
    "strip3": (7, pairs([(0, 1, 2), (2, 3, 4), (4, 5, 6)]), [(0, 1, 2), (2, 3, 4), (4, 5, 6)]),
}
RES = {k: SZ.m2_ideal(m, E, W) for k, (m, E, W) in COVERS.items()}

def parse_entries(s):
    s = s.strip()[1:-1]; rows = []; depth = 0; cur = ""
    for ch in s:
        if ch == "{": depth += 1; cur = "" if depth == 1 else cur + ch; continue
        if ch == "}":
            depth -= 1
            if depth == 0: rows.append(cur); continue
        cur += ch
    return [[x.strip() for x in split_top(r)] for r in rows]

def split_top(r):
    out, cur, d = [], "", 0
    for ch in r:
        if ch in "({": d += 1
        if ch in ")}": d -= 1
        if ch == "," and d == 0: out.append(cur); cur = ""
        else: cur += ch
    out.append(cur); return out

# SZ1
ok = True; info = []
for k, (m, E, W) in COVERS.items():
    R = RES[k]; A, names = SZ.config(m, E, W); rk = np.linalg.matrix_rank(A); n = A.shape[1]
    ok &= R["codim"] == n - rk
    for _ in range(40):
        v = rng.normal(size=m); r = rng.normal(); pt = SZ.model_point(m, E, W, v, r)
        ok &= all(abs(SZ.eval_rel(g, pt)) < 1e-10 for g in R["gens"])
    if R["gens"]:
        bad = {nm: rng.normal() for nm in names}; ok &= any(abs(SZ.eval_rel(g, bad)) > 1e-6 for g in R["gens"])
    info.append(f"{k}: n {n}, rank A {rk}, codim {R['codim']}, gens {len(R['gens'])}")
check("SZ1 generators vanish on the model and not off it; codim I = n - rank A on every cover", ok, "; ".join(info))

# SZ2
ok = True; tot = 0
for k, (m, E, W) in COVERS.items():
    A, _ = SZ.config(m, E, W)
    for i, degs in RES[k]["betti"]:
        for b, cnt in Counter(map(tuple, degs)).items():
            hb = SZ.hochster_betti(A, np.array(b)); ok &= hb.get(i, 0) == cnt; tot += 1
check("SZ2 every multigraded Betti number from Macaulay2 equals the reduced homology of Delta_b (Hochster's formula)", ok, f"{tot} multidegrees")

# SZ3
ok = True; swept = 0
for k in ("bowtie", "C4+012+123"):
    m, E, W = COVERS[k]; A, _ = SZ.config(m, E, W); n = A.shape[1]; known = {}
    for i, degs in RES[k]["betti"]:
        for b, cnt in Counter(map(tuple, degs)).items(): known[(i, b)] = cnt
    seen = set()
    for deg in range(1, 5):
        for u in itertools.combinations_with_replacement(range(n), deg):
            b = tuple(A[:, list(u)].sum(axis=1))
            if b in seen: continue
            seen.add(b); hb = SZ.hochster_betti(A, np.array(b)); swept += 1
            for i, val in hb.items():
                if i >= 1: ok &= known.get((i, b), 0) == val
check("SZ3 no Betti numbers outside Macaulay2's list (bowtie, C4 + two triples; all b = A u with |u| <= 4)", ok, f"{swept} degrees swept")

# SZ4
ok = True; walks = {}
for k, (m, E, W) in COVERS.items():
    B = np.zeros((len(E), m))
    for j, (a, b) in enumerate(E): B[j, a] = B[j, b] = 1
    Rp = SZ.m2_ideal(m, E, []); pair_gens = [g for g in RES[k]["gens"] if "m" not in g]
    ok &= Rp["codim"] == len(E) - np.linalg.matrix_rank(B) and sorted(Rp["gens"]) == sorted(pair_gens)
    walks[k] = pair_gens
check("SZ4 the pair part is the toric ideal of B, codimension |E| - rank B (the modulus class); generators are even closed walks",
      ok, "; ".join(f"{k}: {len(v)}" for k, v in walks.items()))

# SZ5
ok = True; ladder = {}
for k, (m, E, W) in COVERS.items():
    codims = []
    for j in range(len(W) + 1):
        A, _ = SZ.config(m, E, W[:j]); codims.append(A.shape[1] - np.linalg.matrix_rank(A))
    ladder[k] = codims
    A0, _ = SZ.config(m, E, []); free = (m + 1) - np.linalg.matrix_rank(A0)                # r and the bipartite scales
    ok &= all(codims[j + 1] - codims[j] in (0, 1) for j in range(len(W)))
OUT["codim_ladder"] = ladder
check("SZ5 each triple adds 0 (absorbed by r or a scale) or 1 (a second-triple test) to the codimension",
      ok and ladder["bowtie"] == [1, 1, 2] and ladder["C4+012+123"] == [1, 1, 1] and ladder["K4 triples"] == [2, 2, 3, 4, 5], str(ladder))

# SZ6
R = RES["bowtie"]; G = parse_entries(R["diff"][0])[0]; S2 = parse_entries(R["diff"][1])
HB = [["m012", "c01", "c02*c12"], ["m234", "c34", "c23*c24"]]
def minor(i, j): return f"({HB[0][i]})*({HB[1][j]})-({HB[0][j]})*({HB[1][i]})"
ok = True
for _ in range(20):
    pt = {nm: rng.normal() for nm in R["names"]}
    mins = sorted(abs(SZ.eval_rel(minor(i, j), pt)) for i, j in ((0, 1), (0, 2), (1, 2))); gv = sorted(abs(SZ.eval_rel(g, pt)) for g in G)
    ok &= np.allclose(mins, gv)
    gvals = np.array([SZ.eval_rel(g, pt) for g in G]); Sv = np.array([[SZ.eval_rel(x, pt) for x in row] for row in S2])
    ok &= np.allclose(gvals @ Sv, 0)
OUT["bowtie"] = {"gens": G, "syz": S2, "hilbert_burch": HB}
check("SZ6 bowtie = Hilbert-Burch: generators are the 2x2 minors of [[m012, c01, c02 c12], [m234, c34, c23 c24]]; G . Syz = 0",
      ok, f"syzygy matrix {S2}")

# SZ7
def jac(gens, names, pt, h=1e-6):
    out = np.zeros((len(gens), len(names)))
    for j, nm in enumerate(names):
        p1 = dict(pt); p2 = dict(pt); p1[nm] += h; p2[nm] -= h
        out[:, j] = [(SZ.eval_rel(g, p1) - SZ.eval_rel(g, p2)) / (2 * h) for g in gens]
    return out
ok = True; dfinfo = {}
for k in ("bowtie", "fan", "K4 triples", "strip3"):
    m, E, W = COVERS[k]; R = RES[k]; G = parse_entries(R["diff"][0])[0]; S2 = parse_entries(R["diff"][1])
    v = rng.uniform(0.2, 0.6, m) * rng.choice([-1, 1], m); r = rng.uniform(0.3, 1.0); pt = SZ.model_point(m, E, W, v, r)
    Jg = jac(G, R["names"], pt); rk = np.linalg.matrix_rank(Jg, tol=1e-7); Sv = np.array([[SZ.eval_rel(x, pt) for x in row] for row in S2])
    left = np.linalg.matrix_rank(Sv, tol=1e-9); dep = np.abs(Sv.T @ Jg).max()
    rkz = []
    for i in range(m):
        vz = v.copy(); vz[i] = 0.0; ptz = SZ.model_point(m, E, W, vz, r); rkz.append(int(np.linalg.matrix_rank(jac(G, R["names"], ptz), tol=1e-7)))
    dfinfo[k] = dict(gens=len(G), codim=int(R["codim"]), jac_rank=int(rk), syz_rank=int(left), coincidence_rank=rkz)
    ok &= rk == R["codim"] and left == len(G) - R["codim"] and dep < 1e-8
ok &= dfinfo["bowtie"]["coincidence_rank"] == [2, 2, 1, 2, 2]
OUT["tests_df"] = dfinfo
check("SZ7 at a model point the generators' Jacobian has rank codim I and the evaluated syzygies span its left kernel (the dependencies among tests); a coincidence at the bowtie's cut vertex (v_2 = 0) drops the rank, elsewhere not",
      ok, "; ".join(f"{k}: {d['gens']} gens, df {d['jac_rank']}, syz rank {d['syz_rank']}, df at v_i=0 {d['coincidence_rank']}" for k, d in dfinfo.items()))

# SZ8
ok = True; tables = {}
for k, R in RES.items():
    pd = max((i for i, _ in R["betti"]), default=0); ok &= (pd == R["codim"]); tables[k] = [len(d) for _, d in R["betti"]]
OUT["betti"] = tables; OUT["gens"] = {k: R["gens"] for k, R in RES.items()}; OUT["codim"] = {k: R["codim"] for k, R in RES.items()}
check("SZ8 Cohen-Macaulay throughout (projective dimension = codimension); Betti tables recorded", ok, "; ".join(f"{k}: {v}" for k, v in tables.items()))

json.dump(OUT, open(os.path.join(HERE, "..", "lab", "syzygy.json"), "w"), indent=1, default=lambda o: int(o) if hasattr(o, "__int__") else str(o))
print(f"{sum(results)}/{len(results)} passed")
